"""The files pyobsd's systemd mode installs: template unit, generator, polkit rule, shutdown drop-ins.

``pyobsd setup`` writes them, every other call in systemd mode compares them with what's on disk and warns. See
specs/plans/2026-11-25-pyobsd-systemd-mode.md.
"""

from __future__ import annotations

import os
import re
import shlex
from dataclasses import dataclass

# module names that are valid unit instance names without escaping
MODULE_NAME_PATTERN = r"[A-Za-z0-9_.:-]+"

_HEADER = "generated by pyobsd setup, changes are overwritten by the next run"


@dataclass(frozen=True)
class SystemdPaths:
    """Where the files go, changed in tests."""

    unit: str = "/etc/systemd/system/pyobs@.service"
    generator: str = "/etc/systemd/system-generators/pyobs-generator"
    polkit_rule: str = "/etc/polkit-1/rules.d/50-pyobs.rules"
    shutdown_dropins: tuple[str, ...] = (
        "/etc/systemd/system/reboot.target.d/pyobs.conf",
        "/etc/systemd/system/poweroff.target.d/pyobs.conf",
    )


@dataclass(frozen=True)
class SystemdSettings:
    """What the files depend on."""

    pyobsd_exec: str
    config_path: str
    run_path: str
    user: str
    group: str


def render_unit(s: SystemdSettings) -> str:
    return f"""# {_HEADER}
[Unit]
Description=pyobs module %i
Wants=network-online.target
After=network-online.target ejabberd.service
ConditionPathExists=|{s.config_path}/%i.yaml
ConditionPathExists=|{s.config_path}/_%i.yaml
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=notify
NotifyAccess=main
User={s.user}
Group={s.group}
EnvironmentFile=-/etc/default/pyobs
WorkingDirectory={s.run_path}
ExecStart={s.pyobsd_exec} exec %i
Restart=on-failure
RestartSec=10
TimeoutStartSec=120
TimeoutStopSec=30
"""


def render_generator(s: SystemdSettings, paths: SystemdPaths = SystemdPaths()) -> str:
    # must be fast and never fail (man systemd.generator): a missing config directory just means no links
    return f"""#!/bin/sh
# {_HEADER}
# Starts every module whose config file doesn't start with "_" at boot, see "pyobsd setup".
config={shlex.quote(s.config_path)}
wants="$1/multi-user.target.wants"
for f in "$config"/*.yaml; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .yaml)
    case "$name" in
        _*|*.shared) continue ;;
        *[!A-Za-z0-9_.:-]*) continue ;;
    esac
    mkdir -p "$wants" || exit 0
    ln -sf {shlex.quote(paths.unit)} "$wants/pyobs@$name.service" || true
done
exit 0
"""


def render_polkit_rule(s: SystemdSettings) -> str:
    return f"""// {_HEADER}
// Lets {s.user} start, stop, restart and kill pyobs modules, nothing else.
polkit.addRule(function(action, subject) {{
    if (action.id == "org.freedesktop.systemd1.manage-units" &&
        subject.user == "{s.user}" &&
        /^pyobs@{MODULE_NAME_PATTERN}\\.service$/.test(action.lookup("unit") || "") &&
        ["start", "stop", "restart", "kill", "reset-failed"].indexOf(action.lookup("verb")) >= 0) {{
        return polkit.Result.YES;
    }}
}});
"""


def render_shutdown_dropin(minutes: int) -> str:
    return f"""# {_HEADER}
# Gives cooled cameras time to warm up on a reboot or poweroff.
[Unit]
JobTimeoutSec={minutes}min
"""


def read_shutdown_timeout(paths: SystemdPaths = SystemdPaths()) -> int | None:
    """The shutdown timeout in minutes from the first drop-in, or None if there is none."""
    try:
        with open(paths.shutdown_dropins[0]) as f:
            m = re.search(r"^JobTimeoutSec=(\d+)min$", f.read(), re.MULTILINE)
    except OSError:
        return None
    return int(m.group(1)) if m else None


def installed_files(s: SystemdSettings, paths: SystemdPaths = SystemdPaths()) -> dict[str, tuple[str, int]]:
    """Unit, generator and polkit rule, as {filename: (content, mode)}."""
    return {
        paths.unit: (render_unit(s), 0o644),
        paths.generator: (render_generator(s, paths), 0o755),
        paths.polkit_rule: (render_polkit_rule(s), 0o644),
    }


def file_differs(filename: str, content: str) -> bool | None:
    """Whether the file is missing or has other content. None if it can't be read (e.g. the polkit rule as a
    user)."""
    try:
        with open(filename) as f:
            return f.read() != content
    except FileNotFoundError:
        return True
    except OSError:
        return None


def check_installed(s: SystemdSettings, paths: SystemdPaths = SystemdPaths()) -> list[str]:
    """Warnings for missing or outdated files, for calls other than setup."""
    warnings = []
    for filename, (content, _) in installed_files(s, paths).items():
        differs = file_differs(filename, content)
        if differs and not os.path.exists(filename):
            warnings.append(f"{filename} is missing, run pyobsd setup as root.")
        elif differs:
            warnings.append(f"{filename} is outdated, run pyobsd setup as root.")
    return warnings
